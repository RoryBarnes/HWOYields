#!/usr/bin/env python3
"""Generate integrity, qualitative and quantitative tests by introspecting each step's outputs.

This stands in for `vaibify-do generate-tests-deterministic`, which refuses with
`no-project-open` until the researcher opens the project in the dashboard. Like that action it
derives every assertion from what is actually in the declared output files -- real columns, real
JSON keys, real array names, real values -- rather than from a reading of the code, and it
writes the standards it pins alongside the tests. Re-run it after opening the project only if
the backend generator is unavailable; prefer the backend generator when it works.
"""

import argparse
import json
import os

import subprocess

import numpy as np
import pandas as pd

S_SKIP_NUMERIC = ("fMedianTauCharDays",)


def fdictIntrospectJson(sPath):
    """Top-level keys and every finite numeric leaf, each addressed by an explicit key list.

    Paths are lists rather than dotted strings because JSON keys may themselves contain dots --
    an axis-tick map keyed by "0.0" produced the path "dictXTicks.0.0", which no split on "."
    can resolve. Key lists have no such ambiguity.
    """
    with open(sPath) as oFile:
        dictData = json.load(oFile)
    listNumbers = []

    def fnWalk(oNode, listPrefix):
        if isinstance(oNode, dict):
            for sKey, oValue in oNode.items():
                fnWalk(oValue, listPrefix + [sKey])
        elif isinstance(oNode, bool):
            listNumbers.append({"saPath": listPrefix, "oValue": bool(oNode)})
        elif isinstance(oNode, (int, float)) and np.isfinite(oNode):
            listNumbers.append({"saPath": listPrefix, "oValue": float(oNode)})

    fnWalk(dictData, [])
    return {"sKind": "json", "saTopLevelKeys": sorted(dictData.keys()),
            "listNumbers": listNumbers}


def fdictIntrospectCsv(sPath):
    """Column names, row count, and per-column statistics for finite numeric columns."""
    dfData = pd.read_csv(sPath)
    dictStats, saAllFinite = {}, []
    for sCol in dfData.columns:
        if not pd.api.types.is_numeric_dtype(dfData[sCol]):
            continue
        faValues = dfData[sCol].to_numpy(dtype=float)
        if np.all(np.isfinite(faValues)) and faValues.size:
            saAllFinite.append(sCol)
            dictStats[sCol] = {"fMean": float(np.mean(faValues)),
                               "fStd": float(np.std(faValues)),
                               "fMin": float(np.min(faValues)),
                               "fMax": float(np.max(faValues))}
    return {"sKind": "csv", "saColumns": list(dfData.columns), "iRows": int(len(dfData)),
            "saFiniteColumns": saAllFinite, "dictColumnStats": dictStats}


def fdictIntrospectNpz(sPath):
    """Array names, shapes, dtypes and statistics for the finite numeric arrays."""
    dictNpz = np.load(sPath, allow_pickle=True)
    dictArrays, dictStats = {}, {}
    for sName in dictNpz.files:
        faArray = dictNpz[sName]
        dictArrays[sName] = {"listShape": list(faArray.shape), "sDtype": str(faArray.dtype)}
        if faArray.dtype.kind in "fi" and faArray.size:
            faFlat = faArray.astype(float).ravel()
            if np.all(np.isfinite(faFlat)):
                dictStats[sName] = {"fMean": float(np.mean(faFlat)),
                                    "fMin": float(np.min(faFlat)),
                                    "fMax": float(np.max(faFlat))}
    return {"sKind": "npz", "saArrays": sorted(dictNpz.files), "dictArrayMeta": dictArrays,
            "dictArrayStats": dictStats}


def fdictIntrospectFile(sStepDir, sRelPath):
    """Dispatch introspection on a declared output file by extension.

    Declared paths are relative to the STEP directory, which is how vaibify resolves them.
    """
    sPath = os.path.normpath(os.path.join(sStepDir, sRelPath))
    sExt = os.path.splitext(sRelPath)[1].lower()
    dictOut = {".json": fdictIntrospectJson, ".csv": fdictIntrospectCsv,
               ".npz": fdictIntrospectNpz}[sExt](sPath)
    dictOut["iBytes"] = os.path.getsize(sPath)
    return dictOut


