def fnWriteStepTests(sRepoRoot, dictStep, fRtol):
    """Write the three test files and the standards file for one step."""
    sStepDir = os.path.join(sRepoRoot, dictStep["sDirectory"])
    dictFiles = {s: fdictIntrospectFile(sStepDir, s) for s in dictStep["saOutputDataFiles"]}
    with open(os.path.join(sStepDir, "testStandards.json"), "w") as oFile:
        json.dump({"sStep": dictStep["sName"], "dictFiles": dictFiles}, oFile, indent=2)
    for sFileName, sDoc, sBody in (
            ("testIntegrity.py", f"Integrity tests for step {dictStep['sName']}.",
             S_INTEGRITY_BODY),
            ("testQualitative.py", f"Qualitative structure tests for step {dictStep['sName']}.",
             S_QUALITATIVE_BODY),
            ("testQuantitative.py", f"Quantitative tests for step {dictStep['sName']}.",
             S_QUANTITATIVE_BODY.replace("{fRtol}", repr(fRtol)))):
        with open(os.path.join(sStepDir, sFileName), "w") as oFile:
            oFile.write(S_TEST_HEADER.format(sDoc=sDoc) + sBody)
    return len(dictFiles)


def fdictTestsBlock(sDirectory):
    """The dictTests block declaring all three categories for a step.

    Paths are relative to the STEP directory, which is how vaibify resolves every declared
    path in a step (saOutputDataFiles, saPlotFiles, dictTests.sFilePath).
    """
    return {sCategory: {"sFilePath": sFile,
                        "saCommands": [f"python3 -m pytest {sFile} -q"]}
            for sCategory, sFile in (("dictIntegrity", "testIntegrity.py"),
                                     ("dictQualitative", "testQualitative.py"),
                                     ("dictQuantitative", "testQuantitative.py"))}


def fnDeclareTests(dictProject, sProjectPath):
    """Declare every step's dictTests through vaibify-do, falling back to a direct write.

    Writing project.json directly is not safe for a step vaibify has recently created: the
    backend rewrote one step's dictTests to empty commands, which silently disabled its whole
    test suite while leaving the other steps intact. vaibify-do goes through schema validation
    and an atomic save, so it wins the race.
    """
    for i, dictStep in enumerate(dictProject["listSteps"], start=1):
        oResult = subprocess.run(
            ["vaibify-do", "update-step", f"A{i:02d}",
             json.dumps({"dictTests": dictStep["dictTests"]})],
            capture_output=True, text=True, timeout=120)
        if oResult.returncode != 0:
            print(f"WARNING: update-step A{i:02d} failed; writing project.json directly")
            with open(sProjectPath, "w") as oFile:
                json.dump(dictProject, oFile, indent=2)
            return


def fdictParseArgs():
    """Command-line configuration for the test generator."""
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--project", required=True)
    p.add_argument("--repo-root", default="..")
    p.add_argument("--rtol", type=float, default=1e-6)
    return vars(p.parse_args())


def main():
    dictArgs = fdictParseArgs()
    sRepoRoot = os.path.abspath(dictArgs["repo_root"])
    with open(dictArgs["project"]) as oFile:
        dictProject = json.load(oFile)
    dictReport = {}
    for dictStep in dictProject["listSteps"]:
        dictReport[dictStep["sName"]] = fnWriteStepTests(sRepoRoot, dictStep, dictArgs["rtol"])
        dictStep["dictTests"] = fdictTestsBlock(dictStep["sDirectory"])
    fnDeclareTests(dictProject, dictArgs["project"])
    print(json.dumps({"dictFilesPinnedPerStep": dictReport,
                      "sNote": "dictTests declared for every step in " + dictArgs["project"]},
                     indent=2))


if __name__ == "__main__":
    main()
