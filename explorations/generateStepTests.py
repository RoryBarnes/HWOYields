S_QUALITATIVE_BODY = '''

@pytest.mark.parametrize("sRelPath", LIST_FILES)
def test_recorded_structure_is_present(sRelPath):
    """The columns, JSON keys or array names that downstream steps bind to still exist."""
    dictStd = DICT_STANDARDS["dictFiles"][sRelPath]
    sPath = fsResolve(sRelPath)
    if dictStd["sKind"] == "csv":
        saActual = set(pd.read_csv(sPath, nrows=1).columns)
        saMissing = set(dictStd["saColumns"]) - saActual
        assert not saMissing, f"{sRelPath} lost columns: {sorted(saMissing)}"
    elif dictStd["sKind"] == "npz":
        saActual = set(np.load(sPath, allow_pickle=True).files)
        saMissing = set(dictStd["saArrays"]) - saActual
        assert not saMissing, f"{sRelPath} lost arrays: {sorted(saMissing)}"
    else:
        with open(sPath) as oFile:
            saActual = set(json.load(oFile).keys())
        saMissing = set(dictStd["saTopLevelKeys"]) - saActual
        assert not saMissing, f"{sRelPath} lost top-level keys: {sorted(saMissing)}"


@pytest.mark.parametrize("sRelPath", LIST_FILES)
def test_recorded_numeric_json_paths_are_present(sRelPath):
    """Nested JSON paths that carry the step's results are still reachable."""
    dictStd = DICT_STANDARDS["dictFiles"][sRelPath]
    if dictStd["sKind"] != "json":
        pytest.skip("not a JSON output")
    with open(fsResolve(sRelPath)) as oFile:
        dictData = json.load(oFile)
    for dictEntry in dictStd["listNumbers"]:
        oNode = dictData
        for sPart in dictEntry["saPath"]:
            assert isinstance(oNode, dict) and sPart in oNode, dictEntry["saPath"]
            oNode = oNode[sPart]
'''

